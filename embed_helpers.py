"""Helpers for turning a stored reminder into the content sent to Discord."""

import json
from typing import Any

import discord

from Entities.reminder import Reminder
from const import DEFAULT_EMBED_COLOR, EMBED_COLOR_NAMES, EMBED_MAX_TOTAL_LENGTH


def parse_embed_color(value: str) -> int | None:
    """Parse an embed colour given as a name, "#rrggbb" or integer.

    Returns None when the value cannot be parsed.
    """
    value = value.strip()
    if not value:
        return None

    name = value.lower().lstrip("#")
    if name in EMBED_COLOR_NAMES:
        return EMBED_COLOR_NAMES[name]

    if name.isdigit():
        return int(name) & 0xFFFFFF

    if len(name) == 6:
        try:
            return int(name, 16)
        except ValueError:
            return None

    return None


def build_reminder_content(reminder: Reminder) -> dict[str, Any]:
    """Build the keyword arguments for sending a reminder with `send`.

    Plain reminders send their text as content so it can carry mentions. Embeds
    made with the embed builder are sent as stored, with the reminder text above
    them. Other embed reminders use the text as the description, with the
    configured title, colour and footer.
    """
    if reminder.embed_json:
        return {
            "content": reminder.message or None,
            "embed": discord.Embed.from_dict(json.loads(reminder.embed_json)),
        }

    if not reminder.as_embed:
        return {"content": reminder.message}

    embed = discord.Embed(
        description=reminder.message,
        colour=discord.Colour(reminder.embed_color or DEFAULT_EMBED_COLOR),
    )
    if reminder.embed_title:
        embed.title = reminder.embed_title
    if reminder.embed_footer:
        embed.set_footer(text=reminder.embed_footer)
    return {"embed": embed}


def reminder_summary_text(reminder: Reminder) -> str:
    """The text that best describes a reminder in listings."""
    if reminder.message.strip() or not reminder.embed_json:
        return reminder.message
    data = json.loads(reminder.embed_json)
    return data.get("title") or data.get("description") or ""


def copy_message_embed(message: discord.Message) -> tuple[str, discord.Embed | None]:
    """Copy the text and first embed of a message, or of the message it forwards.

    Only rich embeds are copied; link previews are generated by Discord and
    cannot be sent back as they are.
    """
    content = message.content or ""
    embeds = list(message.embeds)
    for snapshot in getattr(message, "message_snapshots", None) or []:
        content = content or snapshot.content or ""
        embeds.extend(snapshot.embeds)

    for embed in embeds:
        if embed.type == "rich":
            return content, discord.Embed.from_dict(embed.to_dict())
    return content, None


def is_embed_url(value: str) -> bool:
    """Whether Discord accepts a value as an embed link or image URL."""
    return value.startswith(("https://", "http://"))


def embed_problem(embed: discord.Embed) -> str | None:
    """Return why Discord would refuse to send an embed, or None when it is fine."""
    has_content = any((
        embed.title, embed.description, embed.fields, embed.image.url,
        embed.thumbnail.url, embed.author.name, embed.footer.text,
    ))
    if not has_content:
        return "The embed is empty. Give it at least a title, description, field or image."
    if len(embed) > EMBED_MAX_TOTAL_LENGTH:
        return f"The embed is too long. Discord allows {EMBED_MAX_TOTAL_LENGTH} characters in total."
    return None
